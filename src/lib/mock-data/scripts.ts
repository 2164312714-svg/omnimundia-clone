/** 按 ID 获取剧本 */
export function getScriptById(id: string): Script | undefined {
  return mockScripts.find((s) => s.id === id);
}

/** 按分类筛选剧本 */
export function getScriptsByCategory(category: string): Script[] {
  if (category === "all") return mockScripts;
  return mockScripts.filter((s) => s.category === category);
}

/** 搜索剧本 */
export function searchScripts(query: string): Script[] {
  const q = query.toLowerCase().trim();
  if (!q) return mockScripts;
  return mockScripts.filter(
    (s) =>
      s.title.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q) ||
      s.author.toLowerCase().includes(q) ||
      s.tags.some((t) => t.toLowerCase().includes(q))
  );
}

/** 获取轮播推荐的剧本（portalFeatured） */
export function getFeaturedScripts(): Script[] {
  return mockScripts.filter((s) => s.portalFeatured);
}
